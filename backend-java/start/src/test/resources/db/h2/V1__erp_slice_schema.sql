CREATE TABLE sys_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL UNIQUE,
    status SMALLINT NOT NULL,
    token_epoch BIGINT DEFAULT 0,
    deleted_at TIMESTAMP WITH TIME ZONE
);
CREATE TABLE sys_roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(64) NOT NULL UNIQUE,
    status SMALLINT NOT NULL,
    deleted_at TIMESTAMP WITH TIME ZONE
);
CREATE TABLE sys_menus (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permission VARCHAR(128) NOT NULL,
    status SMALLINT NOT NULL,
    deleted_at TIMESTAMP WITH TIME ZONE
);
CREATE TABLE sys_user_roles (
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    PRIMARY KEY (user_id, role_id)
);
CREATE TABLE sys_role_menus (
    role_id BIGINT NOT NULL,
    menu_id BIGINT NOT NULL,
    PRIMARY KEY (role_id, menu_id)
);
CREATE TABLE inv_products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(32) NOT NULL,
    name VARCHAR(128) NOT NULL,
    status SMALLINT NOT NULL,
    deleted_at TIMESTAMP WITH TIME ZONE
);
CREATE TABLE inv_product_specs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    spec VARCHAR(64) NOT NULL,
    stock NUMERIC(14,4) DEFAULT 0,
    sort INTEGER NOT NULL DEFAULT 0,
    status SMALLINT NOT NULL,
    deleted_at TIMESTAMP WITH TIME ZONE
);
CREATE TABLE inv_product_units (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    spec_id BIGINT NOT NULL,
    unit VARCHAR(16) NOT NULL,
    is_base BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP WITH TIME ZONE
);
CREATE TABLE inv_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no VARCHAR(32) NOT NULL,
    biz_type VARCHAR(16) NOT NULL,
    party_id BIGINT,
    order_date DATE,
    status SMALLINT NOT NULL,
    total_amount NUMERIC(14,2) DEFAULT 0,
    settled_amount NUMERIC(14,2) DEFAULT 0,
    salesman VARCHAR(64),
    created_by BIGINT,
    auditor_id BIGINT,
    audited_at TIMESTAMP WITH TIME ZONE,
    pending_since TIMESTAMP WITH TIME ZONE,
    updated_at TIMESTAMP WITH TIME ZONE,
    deleted_at TIMESTAMP WITH TIME ZONE
);
CREATE TABLE inv_order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    product_id BIGINT,
    product_name VARCHAR(128),
    spec_id BIGINT,
    spec VARCHAR(64),
    unit_id BIGINT,
    unit VARCHAR(16),
    rate NUMERIC(14,4) DEFAULT 1,
    qty NUMERIC(14,2) DEFAULT 0,
    qty_base NUMERIC(14,4) DEFAULT 0,
    deleted_at TIMESTAMP WITH TIME ZONE
);
CREATE TABLE inv_stock_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no VARCHAR(32) NOT NULL,
    direction VARCHAR(8) NOT NULL,
    source_type VARCHAR(16),
    source_id BIGINT,
    order_date DATE,
    status SMALLINT NOT NULL,
    remark VARCHAR(255),
    salesman VARCHAR(64),
    created_by BIGINT,
    created_at TIMESTAMP WITH TIME ZONE,
    updated_at TIMESTAMP WITH TIME ZONE,
    deleted_at TIMESTAMP WITH TIME ZONE,
    active_order_no VARCHAR(32) GENERATED ALWAYS AS (CASE WHEN deleted_at IS NULL THEN order_no END),
    CONSTRAINT uk_inv_stock_orders_no UNIQUE (active_order_no)
);
CREATE TABLE inv_stock_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_order_id BIGINT NOT NULL,
    product_id BIGINT,
    product_name VARCHAR(128),
    spec_id BIGINT,
    spec VARCHAR(64),
    unit_id BIGINT,
    unit VARCHAR(16),
    rate NUMERIC(14,4) DEFAULT 1,
    qty NUMERIC(14,2) DEFAULT 0,
    qty_base NUMERIC(14,4) DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE,
    updated_at TIMESTAMP WITH TIME ZONE,
    deleted_at TIMESTAMP WITH TIME ZONE
);
CREATE TABLE inv_settlements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    plan_id BIGINT,
    source VARCHAR(16) NOT NULL DEFAULT 'order',
    biz_type VARCHAR(16),
    party_id BIGINT,
    amount NUMERIC(14,2) DEFAULT 0,
    method VARCHAR(32),
    settled_at DATE,
    remark VARCHAR(255),
    created_by BIGINT,
    kind VARCHAR(24) NOT NULL DEFAULT '',
    reference VARCHAR(128) NOT NULL DEFAULT '',
    created_at TIMESTAMP WITH TIME ZONE,
    updated_at TIMESTAMP WITH TIME ZONE,
    deleted_at TIMESTAMP WITH TIME ZONE
);
CREATE TABLE inv_order_audits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    order_no VARCHAR(32) NOT NULL,
    action VARCHAR(16) NOT NULL,
    actor_id BIGINT NOT NULL,
    actor_name VARCHAR(128) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    stock_order_id BIGINT
);
