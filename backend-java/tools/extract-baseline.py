menus=[]
def parse_nodes(text,parent=0):
 nodes=[];i=0
 while i<len(text):
  if text[i]!='{':i+=1;continue
  start=i;depth=1;i+=1;quote=False;escape=False
  while i<len(text) and depth:
   c=text[i]
   if c=='"' and not escape:quote=not quote
   if not quote:
    if c=='{':depth+=1
    if c=='}':depth-=1
   escape=(c=='\\' and not escape);i+=1
  block=text[start+1:i-1];head=block.split('Children:')[0];node={'id':len(menus)+1,'parentId':parent,'status':1,'type':'menu','sort':len(nodes)+1}
  for k,v in re.findall(r'(Name|Title|Icon|Path|Component|Redirect|Permission):\s*"([^"]*)"',head):node[k[0].lower()+k[1:]]=v
  if 'name' not in node:continue
  for k,v in re.findall(r'(KeepAlive|Hidden|IsExternal):\s*(true|false)',head):node[k[0].lower()+k[1:]]=v=='true'
  ty=re.search(r'Type:\s*module.Type(Dir|Button)',head)
  if ty:node['type']=ty[1].lower()
  so=re.search(r'Sort:\s*(\d+)',head)
  if so:node['sort']=int(so[1])
  menus.append(node);nodes.append(node)
  if 'Children:' in block:parse_nodes(block.split('Children:',1)[1].split('{',1)[1].rsplit('}',1)[0],node['id'])
 return nodes
