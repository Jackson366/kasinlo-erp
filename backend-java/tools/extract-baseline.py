"""Capture Go schema, menu declarations and HTTP contracts for Java migration.
Generated files are reviewed and committed; Java runtime has no Go dependency.
"""
import re,json,pathlib
root=pathlib.Path(__file__).resolve().parents[2]; out=root/'backend-java/src/main/resources'; out.mkdir(parents=True,exist_ok=True)
def snake(n):
 n=re.sub(r'([A-Z]+)([A-Z][a-z])',r'\1_\2',n); return re.sub(r'([a-z0-9])([A-Z])',r'\1_\2',n).lower()
models={}; ddl=[]
for p in (root/'backend/internal/model').glob('*.go'):
 s=p.read_text()
 for name,body in re.findall(r'type (\w+) struct \{(.*?)\n\}',s,re.S):
  tm=re.search(r'func \('+name+r'\) TableName\(\) string \{ return "([^"]+)"',s)
  if not tm: continue
  fields={}
  if re.search(r'^\s*BaseModel\s*$',body,re.M): fields.update({'id':{'column':'id','type':'long'},'createdAt':{'column':'created_at','type':'time'},'updatedAt':{'column':'updated_at','type':'time'},'deletedAt':{'column':'deleted_at','type':'time'}})
  for field,typ,tag in re.findall(r'^\s*(\w+)\s+(\S+)\s+`([^`]+)`',body,re.M):
   if typ.startswith('[]') or typ.lstrip('*') not in ['string','bool','int','int16','int64','uint','uint64','float64','time.Time','gorm.DeletedAt']: continue
   g=re.search(r'gorm:"([^"]+)"',tag); g=g[1] if g else ''
   if g=='-':continue
   j=re.search(r'json:"([^",]+)',tag); j=j[1] if j and j[1]!='-' else field[0].lower()+field[1:]
   col=re.search(r'column:([^;]+)',g); col=col[1] if col else snake(field)
   kind='decimal' if typ=='float64' else 'bool' if typ=='bool' else 'time' if 'Time' in typ or 'DeletedAt' in typ else 'string' if typ=='string' else 'long'
   fields[j]={'column':col,'type':kind,'optional':typ.startswith('*') or j=='deletedAt'}
   size=re.search(r'size:(\d+)',g)
   if size:fields[j]['max']=int(size[1])
   nt=re.search(r'type:(numeric\([^)]+\)|date|text)',g)
   if nt:fields[j]['sqlType']=nt[1]
  table=tm[1];models[table]=fields
  cols=[]
  for j,f in fields.items():
   if f['column']=='id':sql='BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'
   elif f['type']=='long':sql='BIGINT NOT NULL DEFAULT 0' if table in ('sys_user_roles','sys_role_menus') else 'BIGINT DEFAULT 0'
   elif f['type']=='bool':sql='BOOLEAN DEFAULT FALSE'
   elif f['type']=='decimal':sql=f.get('sqlType','NUMERIC(18,4)')+' DEFAULT 0'
   elif f['type']=='time':sql='DATE' if f.get('sqlType')=='date' else 'TIMESTAMP WITH TIME ZONE'
   else:sql=('VARCHAR('+str(f['max'])+')' if 'max' in f else 'TEXT')+" DEFAULT ''"
   cols.append('\"'+f['column']+'\" '+sql)
  ddl.append('CREATE TABLE '+table+' (\n  '+',\n  '.join(cols)+'\n);')
# Join tables have composite primary keys.
for t,cs in [('sys_user_roles','user_id,role_id'),('sys_role_menus','role_id,menu_id')]:ddl.append('ALTER TABLE '+t+' ADD PRIMARY KEY ('+cs+');')
(out/'schema-metadata.json').write_text(json.dumps(models,ensure_ascii=False,indent=2))
mig=out/'db/migration';mig.mkdir(parents=True,exist_ok=True);(mig/'V1__initial_schema.sql').write_text('\n\n'.join(ddl))
routes=[]
for p in (root/'backend/internal/module').glob('*/route.go'):
 s=re.sub(r'//[^\n]*','',p.read_text());group=re.search(r'g := rg.Group\("([^"]+)"',s)
 if not group:continue
 for method,path,args,handler in re.findall(r'g\.(GET|POST|PUT|DELETE|PATCH)\("([^"]*)",\s*(.*?)h\.(\w+)\)',s,re.S):
  perms=[]
  for per in re.findall(r'RequirePerm\((.*?)\)',args):perms+=re.findall(r'"([^"]+)"',per)
  routes.append({'method':method,'path':'/api/v1'+group[1]+path,'module':p.parent.name,'handler':handler,'permissions':perms})
routes.sort(key=lambda r:r['path'].count(':'))
(out/'routes.json').write_text(json.dumps(routes,ensure_ascii=False,indent=2))
